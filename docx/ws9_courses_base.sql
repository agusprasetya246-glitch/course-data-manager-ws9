create table public.courses (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  credits integer not null check (credits > 0),
  status text not null default 'planned'
    check (status in ('planned', 'active', 'done')),
  created_at timestamptz not null default now()
);

alter table public.courses enable row level security;

create policy "lab: anon boleh baca dan tulis courses"
on public.courses for all
to anon
using (true) with check (true);

grant select, insert, update, delete on public.courses to anon;
grant usage, select on sequence public.courses_id_seq to anon;

